#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CardActivation {
    Passive,
    Active,
    Rule,
}

#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub enum CardPhase {
    Opening,
    Middle,
    End,
    Piece,
    Rule,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ImplementedCardDefinition {
    pub id: &'static str,
    pub name_ko: &'static str,
    pub effect: &'static str,
    pub activation: CardActivation,
    pub phase: CardPhase,
    pub half_stars: u16,
    pub ends_turn: bool,
    pub turn_exclusive: bool,
}

const fn middle_card(
    id: &'static str,
    name_ko: &'static str,
    effect: &'static str,
    half_stars: u16,
    activation: CardActivation,
    ends_turn: bool,
    turn_exclusive: bool,
) -> ImplementedCardDefinition {
    ImplementedCardDefinition {
        id,
        name_ko,
        effect,
        activation,
        phase: CardPhase::Middle,
        half_stars,
        ends_turn,
        turn_exclusive,
    }
}

const fn end_card(
    id: &'static str,
    name_ko: &'static str,
    effect: &'static str,
    half_stars: u16,
    activation: CardActivation,
    ends_turn: bool,
    turn_exclusive: bool,
) -> ImplementedCardDefinition {
    ImplementedCardDefinition {
        id,
        name_ko,
        effect,
        activation,
        phase: CardPhase::End,
        half_stars,
        ends_turn,
        turn_exclusive,
    }
}

const fn rule_card(
    id: &'static str,
    name_ko: &'static str,
    effect: &'static str,
    half_stars: u16,
) -> ImplementedCardDefinition {
    ImplementedCardDefinition {
        id,
        name_ko,
        effect,
        activation: CardActivation::Rule,
        phase: CardPhase::Rule,
        half_stars,
        ends_turn: false,
        turn_exclusive: false,
    }
}

